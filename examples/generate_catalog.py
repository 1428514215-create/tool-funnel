# Cross-domain handoffs that make the "no hard isolation" story concrete.
BRIDGES = {
    "order": ["logistics", "after_sales", "finance"],
    "logistics": ["order", "inventory"],
    "after_sales": ["order", "finance", "crm"],
    "inventory": ["logistics", "product"],
    "crm": ["marketing", "after_sales"],
    "marketing": ["crm", "analytics"],
    "product": ["media", "inventory"],
    "media": ["product", "marketing"],
    "analytics": ["finance", "marketing"],
    "finance": ["order", "analytics"],
}


def build_catalog(target_tools: int = 1000) -> Dict[str, Any]:
    domains: List[Dict[str, Any]] = []
    stages: List[Dict[str, Any]] = []
    for en, zh, sts, _verbs, _nouns in DOMAIN_BLUEPRINTS:
        stages.extend(
            {"name": st, "domain": en, "order": i, "triggers": trig}
            for i, (st, trig) in enumerate(sts)
        )
        domains.append(
            {
                "name": en,
                "description": f"{zh}业务域",
                "triggers": [zh, en] + [t for _s, trig in sts for t in trig],
                "bridges": BRIDGES.get(en, []),
                "prior": 1.1,
            }
        )

    # Build every (domain, stage) cell, then round-robin one tool per cell so
    # that a small ``target_tools`` still spreads evenly across domains instead
    # of exhausting the first domains before reaching the last.
    cells: List[List[Dict[str, Any]]] = []
    for en, zh, sts, verbs, nouns in DOMAIN_BLUEPRINTS:
        for (stage, _trig) in sts:
            cell: List[Dict[str, Any]] = []
            for verb in verbs:
                for noun in nouns:
                    name = f"{en}__{stage}__{verb}_{noun}"
                    produces = (
                        [f"{en}_id"]
                        if stage in ("locate", "query", "track", "profile")
                        else []
                    )
                    cell.append(
                        {
                            "name": name,
                            "domain": en,
                            "stage": stage,
                            "description": f"{zh}{stage}阶段：{verb} {noun}",
                            "keywords": [noun, zh, stage, verb],
                            "produces": produces,
                            "params": [
                                {"name": "keyword", "type": "string", "required": False},
                                {
                                    "name": f"{en}_id",
                                    "type": "string",
                                    "required": False,
                                    "aliases": ["id"],
                                    "description": f"{zh}唯一标识",
                                },
                            ],
                        }
                    )
            cells.append(cell)

    tools: List[Dict[str, Any]] = []
    stage_tools: Dict[tuple, List[str]] = {}
    depth = 0
    while len(tools) < target_tools:
        progressed = False
        for cell in cells:
            if depth >= len(cell):
                continue
            progressed = True
            t = cell[depth]
            tools.append(t)
            stage_tools.setdefault((t["domain"], t["stage"]), []).append(t["name"])
            if len(tools) >= target_tools:
                break
        if not progressed:
            break
        depth += 1

    # If the unique-cell ceiling is below the target, pad with numbered
    # variants so callers can request an exact catalog size.
    variant = 0
    while len(tools) < target_tools:
        base = tools[variant % len(tools)]
        clone = dict(base)
        clone["name"] = f"{base['name']}__v{(variant // len(tools)) + 2}"
        clone["keywords"] = list(base["keywords"])
        tools.append(clone)
        stage_tools.setdefault((clone["domain"], clone["stage"]), []).append(clone["name"])
        variant += 1
        if variant > target_tools * 4:  # safety valve
            break

    # Wire next_hint edges through each domain's stage order.
    for en, _zh, sts, _v, _n in DOMAIN_BLUEPRINTS:
        order = [s for s, _t in sts]
        for i, stage in enumerate(order):
            if i + 1 >= len(order):
                continue
            nxt = order[i + 1]
            successors = stage_tools.get((en, nxt), [])[:3]
            for name in stage_tools.get((en, stage), []):
                for t in tools:
                    if t["name"] == name:
                        t["next_hint"] = successors
                        break

    # Enrich descriptions so token cost is realistic (real schemas are verbose).
    for t in tools:
        t["description"] = (
            f"{t['description']}。用于{t['domain']}业务域{t['stage']}阶段，"
            f"支持按关键字与标识精确匹配，返回结构化结果。"
        )

    return {
        "config": {"top_domains": 2, "max_tools": 6, "max_bridges": 3, "chain_width": 4},
        "domains": domains,
        "stages": stages,
        "tools": tools,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tools", type=int, default=1000)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "catalog.json"))
    args = ap.parse_args()
    doc = build_catalog(args.tools)
    with open(args.out, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, ensure_ascii=False, indent=1)
    print(f"wrote {args.out}: {len(doc['tools'])} tools, "
          f"{len(doc['domains'])} domains, {len(doc['stages'])} stages")


if __name__ == "__main__":
    main()
