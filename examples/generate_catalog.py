"""Generate a realistic ~1000-tool, multi-domain catalog as a compose document.

The point is to demonstrate the funnel at a scale where the naive approach
(one flat schema list per turn) genuinely hurts. The generator is deterministic
so benchmarks are reproducible and the committed ``catalog.json`` can be
regenerated byte-for-byte.

Run::

    python examples/generate_catalog.py            # writes examples/catalog.json
    python examples/generate_catalog.py --tools 3000
"""

